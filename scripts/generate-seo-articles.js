// Fonction pour générer tous les articles
function generateAllArticles() {
  const blogDir = path.join(__dirname, '../public/content/blog');

  if (!fs.existsSync(blogDir)) {
    fs.mkdirSync(blogDir, { recursive: true });
  }

  let createdCount = 0;

  SEO_ARTICLES.forEach(article => {
    const filename = `${article.id}.json`;
    const filepath = path.join(blogDir, filename);

    const articleData = {
      id: article.id,
      title: article.title,
      excerpt: article.excerpt,
      content: article.content.trim(),
      tags: article.tags,
      coverImage: `/images/blog/${article.id}.jpg`,
      author: 'TaxiAssur',
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
      status: 'published',
      faq: []
    };

    fs.writeFileSync(filepath, JSON.stringify(articleData, null, 2));
    console.log(`✅ Article créé : ${filename}`);
    createdCount++;
  });

  console.log(`\n🎉 ${createdCount} articles SEO générés avec succès !`);
  console.log(`📁 Emplacement : ${blogDir}`);
}

